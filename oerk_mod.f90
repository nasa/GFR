subroutine update_OERK(nst,Apply_Filter,Apply_Limiter)
  !
  !.. Use Statements ..
  use geomvar_mod, only : n_solpts
  use flowvar_mod, only : residual,usp,uoldsp,rk_sum,dtsp
  use ovar,        only : time
  use rhs_mod,     only : stabilize_usp
  !
  !.. Formal Arguments ..
  integer,     intent(in) :: nst
  logical(lk), intent(in) :: Apply_Filter
  logical(lk), intent(in) :: Apply_Limiter
  !
  !.. Local Scalars ..
  integer  :: n,m,nr
  real(wp) :: c,b,g1,g2,g3,d,dt
  real(wp) :: u1ec,u1mx,u1my,u1mz,u1ee,u1m
  real(wp) :: u2ec,u2mx,u2my,u2mz,u2ee,u2m
  !
  !. Local Saved Scalars ..
  integer, save :: idx = -1
  !
  !.. Local Parameters ..
  character(len=*), parameter :: pname = "update_OERK"
  !
continue
  !
  call solver_timer(entering_procedure,pname,idx)
  !
  call debug_timer(entering_procedure,pname)
  !
  if (nst == 1) then
    pseudo_time = time
    rk_sum(:,:) = zero
  end if
  !
  c  = oerk_coef_c(nst)
  b  = oerk_coef_b(nst)
  g1 = oerk_coef_g1(nst)
  g2 = oerk_coef_g2(nst)
  g3 = oerk_coef_g3(nst)
  d  = oerk_coef_d(nst)
  !
  pseudo_time = pseudo_time + c*dtsp(1)
  !
  nr = nme-nmb+1
  !
  if (nr == 3 .and. ncs == 0 .and. .not.force_nd_subroutines) then
    !$ACC PARALLEL LOOP PRESENT(usp,uoldsp,dtsp,residual,rk_sum)
    do n = 1,n_solpts
      !
      dt = b*dtsp(n)
      !
      u1ec = usp(n,nec)
      u1mx = usp(n,nmx)
      u1my = usp(n,nmy)
      u1mz = usp(n,nmz)
      u1ee = usp(n,nee)
      !
      u2ec = rk_sum(n,nec) + d*u1ec
      u2mx = rk_sum(n,nmx) + d*u1mx
      u2my = rk_sum(n,nmy) + d*u1my
      u2mz = rk_sum(n,nmz) + d*u1mz
      u2ee = rk_sum(n,nee) + d*u1ee
      !
      usp(n,nec) = g2*u2ec + g1*u1ec + g3*uoldsp(n,nec) + dt*residual(n,nec)
      usp(n,nmx) = g2*u2mx + g1*u1mx + g3*uoldsp(n,nmx) + dt*residual(n,nmx)
      usp(n,nmy) = g2*u2my + g1*u1my + g3*uoldsp(n,nmy) + dt*residual(n,nmy)
      usp(n,nmz) = g2*u2mz + g1*u1mz + g3*uoldsp(n,nmz) + dt*residual(n,nmz)
      usp(n,nee) = g2*u2ee + g1*u1ee + g3*uoldsp(n,nee) + dt*residual(n,nee)
      !
      rk_sum(n,nec) = u2ec
      rk_sum(n,nmx) = u2mx
      rk_sum(n,nmy) = u2my
      rk_sum(n,nmz) = u2mz
      rk_sum(n,nee) = u2ee
      !
    end do
  else if (nr == 2 .and. ncs == 0 .and. .not.force_nd_subroutines) then
    !$ACC PARALLEL LOOP PRESENT(usp,uoldsp,dtsp,residual,rk_sum)
    do n = 1,n_solpts
      !
      dt = b*dtsp(n)
      !
      u1ec = usp(n,nec)
      u1mx = usp(n,nmx)
      u1my = usp(n,nmy)
      u1ee = usp(n,nee)
      !
      u2ec = rk_sum(n,nec) + d*u1ec
      u2mx = rk_sum(n,nmx) + d*u1mx
      u2my = rk_sum(n,nmy) + d*u1my
      u2ee = rk_sum(n,nee) + d*u1ee
      !
      usp(n,nec) = g2*u2ec + g1*u1ec + g3*uoldsp(n,nec) + dt*residual(n,nec)
      usp(n,nmx) = g2*u2mx + g1*u1mx + g3*uoldsp(n,nmx) + dt*residual(n,nmx)
      usp(n,nmy) = g2*u2my + g1*u1my + g3*uoldsp(n,nmy) + dt*residual(n,nmy)
      usp(n,nee) = g2*u2ee + g1*u1ee + g3*uoldsp(n,nee) + dt*residual(n,nee)
      !
      rk_sum(n,nec) = u2ec
      rk_sum(n,nmx) = u2mx
      rk_sum(n,nmy) = u2my
      rk_sum(n,nee) = u2ee
      !
    end do
  else
    !$ACC PARALLEL LOOP COLLAPSE(2) PRESENT(usp,uoldsp,dtsp,residual,rk_sum)
    do m = 1,nq
      do n = 1,n_solpts
        !
        u1m = usp(n,m)
        !
        u2m = rk_sum(n,m) + d*u1m
        !
        usp(n,m) = g2*u2m + g1*u1m + g3*uoldsp(n,m) + b*dtsp(n)*residual(n,m)
        !
        rk_sum(n,m) = u2m
        !
      end do
    end do
  end if
  !
  ! Apply filtering or limiting to stabilize the solution, and then update
  ! the thermodynamic and transport properties at the solution points
  !
  call stabilize_usp(nst,Apply_Filter,Apply_Limiter,caller_name=pname)
  !
  call debug_timer(leaving_procedure,pname)
  !
  call solver_timer(leaving_procedure,pname,idx)
  !
end subroutine update_OERK
